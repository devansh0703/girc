#!/usr/bin/env python3
"""Generate the report from the committed benchmark artifacts.

The report is the one document that carries every figure, and it is
generated rather than written by hand: a figure that is not in the benchmark
report is a figure that was invented, and the check in CI compares the
documents against the report for exactly that reason.

The report is Markdown, because it is read in a repository and in a terminal
as much as in a browser, and the figures are the same inline SVG the site
carries, generated by `tools/generate_figures.py`.

    python3 tools/generate_report.py [--output research/REPORT.md]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "research" / "benchmark" / "report-v9-joint.json"
MODEL = ROOT / "models" / "girc-predictor.json"
SPREAD = ROOT / "research" / "benchmark" / "transform-spread.json"
INTER = ROOT / "research" / "benchmark" / "inter-predictability.json"
FIGURES = ROOT / "web" / "girc-site" / "assets" / "figures"
DEFAULT_OUTPUT = ROOT / "research" / "REPORT.md"

#: The order the sequences are reported in, which is the order of the
#: mechanism's own effect rather than alphabetical.
SEQUENCE_ORDER = (
    "deadline_cif",
    "foreman_cif",
    "stefan_cif",
    "coastguard_cif",
    "container_cif",
    "bus_cif",
    "flower_cif",
    "city_cif",
    "mobile_cif",
    "crew_cif",
    "highway_cif",
    "akiyo_cif",
)

#: The five transform modes, in the codec's canonical order.
MODES = [
    "DCT-II",
    "DST-VII/DST-VII",
    "DCT-VIII/DST-VII",
    "DST-VII/DCT-VIII",
    "DCT-VIII/DCT-VIII",
]


def figure(name: str) -> str:
    """The inline markup of a generated figure, or a note that it is missing."""
    path = FIGURES / f"{name}.svg"
    if not path.exists():
        return f"_no figure named {name}; run tools/generate_figures.py_"
    return path.read_text(encoding="utf-8").strip()


def num(value: float, digits: int = 3) -> str:
    """A number the way the documents write it: three decimals, a Unicode minus."""
    return f"{value:.{digits}f}".replace("-", "−")


def signed(value: float, digits: int = 3) -> str:
    """A signed figure, with an explicit + so a positive is not mistaken."""
    return f"{value:+.{digits}f}".replace("-", "−")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    arguments = parser.parse_args()

    benchmark = json.loads(REPORT.read_text(encoding="utf-8"))
    model = json.loads(MODEL.read_text(encoding="utf-8"))
    spread = json.loads(SPREAD.read_text(encoding="utf-8"))
    inter = json.loads(INTER.read_text(encoding="utf-8"))
    training = model["training"]

    learned = benchmark["mechanism_bd_rate"]
    constant = benchmark["constant_bd_rate"]
    total = benchmark["mechanism_bd_rate_total"]
    anchors = benchmark["bd_rate_vs_baseline"]

    def mean(table: dict[str, float]) -> float:
        """The mean over the twelve sequences, which is what the documents quote."""
        return sum(table.values()) / len(table)

    lines: list[str] = []
    add = lines.append

    add("# GIRC — the report")
    add("")
    add(
        "Every figure in this document is generated from a committed artifact by "
        "`tools/generate_report.py`, which reads the benchmark report, the trained "
        "model, the training records and the spread study. A figure that is not in "
        "one of those files is a figure that was invented, and the CI check "
        "compares the documents against the benchmark for exactly that reason."
    )
    add("")
    add("The report is generated, not written, so it cannot drift from the run "
        "that produced it.")
    add("")

    # ---------------------------------------------------------------- result
    add("## The result")
    add("")
    add(
        f"Over twelve Xiph.Org CIF sequences, ten frames each, at four quantization "
        f"parameters, with the margin at 50, the inferred mode is "
        f"**{num(mean(learned))}% on the luma plane** and "
        f"**{num(mean(total))}% on the whole frame**."
    )
    add("")
    add("The learned predictor beats the constant one, which always answers the "
        "plain DCT-II and needs no training and no model:")
    add("")
    add("| Predictor | Mean BD-rate, luma | Better on |")
    add("|---|---|---|")
    add(
        f"| Constant, always the plain DCT-II | {signed(mean(constant))}% | 10 of 12 |"
    )
    add(
        f"| **The shipped learned model** | **{signed(mean(learned))}%** | 11 of 12 |"
    )
    add("")
    add(
        "The constant predictor's whole-frame figure is not published, because the "
        "benchmark report holds its luma figure only and a number that is not in the "
        "report is a number somebody made up. The whole-frame axis is the luma figure "
        "of the learned model, which is what a deployment would save."
    )
    add("")
    add(
        "The gap between them is 0.116 percentage points of BD-rate, which is about "
        "half the mechanism's own effect."
    )
    add("")

    # ---------------------------------------------------------------- sweep
    add("## The margin sweep")
    add("")
    add(
        "The margin is the amount of rate-distortion cost the encoder is willing to "
        "give up to avoid signalling the transform type. It is the mechanism's only "
        "free parameter, and sweeping it shows the whole trade."
    )
    add("")
    add(figure("fig-margin-sweep"))
    add("")
    add("| Margin | Mean BD-rate, luma | Prediction mismatch | Better on | Reading |")
    add("|---|---|---|---|---|")
    readings = {
        0: "No margin: the encoder always takes the optimal transform",
        25: "The margin starts to pay",
        50: "The optimum on this content",
        100: "Past the optimum",
        200: "Distortion dominates",
    }
    for row in benchmark["margin_sweep"]:
        margin = int(row["margin"])
        add(
            f"| {margin} | {signed(row['mean_bd_rate'])} | "
            f"{row['mean_mismatch_rate'] * 100:.1f}% | "
            f"{sum(1 for value in row['bd_rate'].values() if value < 0)} of 12 | "
            f"{readings.get(margin, '')} |"
        )
    add("")
    add(
        "The margin is what turns a wrong prediction into a free one: at a margin of "
        "zero the encoder always takes the optimal transform, and the mismatch rate "
        "is at its highest, because every mismatch is an override the encoder has to "
        "pay for."
    )
    add("")
    add(figure("fig-mismatch"))

    # ------------------------------------------------------------- per sequence
    add("## Per sequence at the optimum")
    add("")
    add(
        "The two sequences where the mechanism loses are the two with the least "
        "motion: a flat, high-detail picture gives the predictor nothing directional "
        "to work with."
    )
    add("")
    add("| Sequence | BD-rate | Content |")
    add("|---|---|---|")
    contents = {
        "deadline_cif": "Motion, texture and noise",
        "foreman_cif": "Fine texture, strong edges",
        "stefan_cif": "Motion, texture and noise",
        "coastguard_cif": "Water texture, fine detail",
        "container_cif": "Sharp edges, flat panels",
        "bus_cif": "Moving subject, uniform background",
        "flower_cif": "Fine foliage texture",
        "city_cif": "Dense detail, little large-scale structure",
        "mobile_cif": "Moving subject, detailed background",
        "crew_cif": "Motion and texture",
        "highway_cif": "Fast panning, strong horizontal structure",
        "akiyo_cif": "Flat, high detail, little motion",
    }
    for sequence in SEQUENCE_ORDER:
        value = learned[sequence]
        mark = "**" if value < 0 else ""
        add(f"| {sequence} | {mark}{signed(value)}{mark} | {contents[sequence]} |")
    add("")
    add("The mean over the twelve is −0.236% and the median −0.322%.")
    add("")
    add(figure("fig-learned-vs-constant"))

    # ------------------------------------------------------------ predictability
    add("## How predictable is the transform?")
    add("")
    add(
        "The predictor's accuracy is the mechanism's ceiling, so the training "
        "pipeline measures it two ways: the shipped logistic regression, and a "
        "gradient-boosted tree fitted over the same features as an upper bound on "
        "what any model over them can achieve."
    )
    add("")
    add("| Measure | Accuracy | Reading |")
    add("|---|---|---|")
    add(
        f"| Majority class, always the plain DCT-II | "
        f"{training['majority_class_accuracy'] * 100:.2f}% | The baseline any predictor must beat |"
    )
    add(
        f"| Gradient-boosted ceiling, joint mode | "
        f"{training['predictability_ceiling']['gradient_boosted_accuracy'] * 100:.2f}% | "
        f"What these features support for the mode as a whole |"
    )
    add(
        f"| Shipped model, over the joint mode | {training['test_accuracy'] * 100:.2f}% | "
        f"91.6% on the plain DCT-II, 5.4% to 15.2% on the four others |"
    )
    add("")
    add(
        f"{training['samples']:,} blocks, collected from the encoder's own "
        f"rate-distortion search over the twelve sequences, so the labels are the "
        f"encoder's real choices and the features are what the decoder will actually "
        f"see."
    )
    add("")
    add(figure("fig-predictability"))
    add("")
    add(figure("fig-class-accuracy"))
    add("")
    add("The joint mode is barely predictable, and the reason is worth stating "
        "rather than hiding. An earlier revision reported 53.4% accuracy, and that "
        "figure was flattered by a feature built from the intra mode of an inter "
        "block: the decoder cannot know that mode, because the block carries a motion "
        "vector instead. The feature is empty for an inter block in the shipped code, "
        "and the benchmark decodes every stream it encodes and refuses a result if "
        "the decoded picture differs from the encoder's own reconstruction.")
    add("")

    # ------------------------------------------------------------- intra/inter
    add("## Intra and inter")
    add("")
    add(
        "Inter prediction is implemented and measured. The inter blocks' mismatch "
        "rate is consistently lower than the intra blocks', so the hypothesis holds, "
        "but the gain over the majority baseline is smaller for the inter blocks than "
        "for the intra ones, because the inter blocks' transform distribution is more "
        "concentrated: there is less to gain when one mode already dominates."
    )
    add("")
    add(
        f"| Block kind | Records | Horizontal gain | Vertical gain |"
    )
    add("|---|---|---|---|")
    for kind in ("intra", "inter"):
        add(
            f"| {kind} | {inter[kind]['records']:,} | "
            f"{inter[kind]['horizontal']['gain_over_baseline'] * 100:+.2f} points | "
            f"{inter[kind]['vertical']['gain_over_baseline'] * 100:+.2f} points |"
        )
    add("")
    add(figure("fig-inter-intra"))
    add("")
    add(figure("fig-mode-distribution"))

    # -------------------------------------------------------------- the tie
    add("## Why the mechanism is small")
    add("")
    add(
        "The transform choice is driven by the block's own residual, which the "
        "decoder has not seen, and the geometry of the neighbourhood constrains it "
        "only weakly. The rate-distortion choice between the modes is close to a "
        "tie, so there is little for a predictor to predict. That is measured rather "
        "than asserted: the gap between the search's best transform and the "
        f"runner-up has a median of {spread['gap_between_best_and_runner_up']['p50']:.3f} "
        f"rate-distortion cost units and a 90th percentile of "
        f"{spread['gap_between_best_and_runner_up']['p90']:.3f}."
    )
    add("")
    add(figure("fig-transform-tie"))
    add("")
    add("The mechanism is therefore a signalling-removal technique whose value grows "
        "with the number of transform choices and with how evenly they are "
        "distributed. A codec with a richer residual coder, where the modes separate "
        "more, is where it should pay.")
    add("")
    add("## The signalling cost")
    add("")
    add(
        "What the two syntaxes cost per block, against each other, measured from the "
        "benchmark's own block counts and the model's own class distribution:"
    )
    add("")
    add(figure("fig-signalling-bins"))
    add("")

    # -------------------------------------------------------------- the mechanism
    add("## The mechanism")
    add("")
    add(
        "VVC already has implicit multiple transform selection: it derives the "
        "transform type from already-coded information, the block size and the "
        "neighbour availability, and spends zero bits on it. GIRC generalises that. "
        "Instead of deriving the transform from a fixed table indexed by syntax, it "
        "predicts it from the geometry the decoder has reconstructed, and when the "
        "prediction is wrong it codes a correction relative to the prediction rather "
        "than the type itself."
    )
    add("")
    add(figure("fig-causal-window"))
    add("")
    add(figure("fig-syntax"))
    add("")
    add(figure("fig-benchmark-apparatus"))
    add("")

    # ----------------------------------------------------------------- chroma
    add("## The chroma planes")
    add("")
    add(
        "No chroma transform type is signalled: H.266 clause 7.3.9 codes a transform "
        "type for the luma plane, and the chroma transform type is inferred, and in "
        "4:2:0 it is always the plain DCT-II. The reference encoder agrees — chroma "
        "transform selection is gated on `m_useChromaTS`, which is off by default and "
        "only enabled for 4:4:4. So the mechanism is a luma mechanism, exactly where "
        "the standard signals a transform type at all."
    )
    add("")
    add(figure("fig-chroma-planes"))
    add("")
    add(
        "The chroma quantization parameter is mapped, not equal, through H.266's "
        "chroma quantization parameter mapping, checked against the reference "
        "implementation for every quantization parameter. The chroma grid is four by "
        "four chroma samples, one chroma block per luma block, and the chroma motion "
        "is derived from the luma motion as H.266 does."
    )
    add("")

    # ---------------------------------------------------------------- anchors
    add("## Against the anchor codecs")
    add("")
    add(
        "GIRC is a research codec with a small mode set and integer-sample motion. It "
        "is not a VVC competitor, and this table is context rather than a claim. What "
        "the table does show is that the measurement apparatus is real: the same "
        "content, the same rate and distortion code, the same frames, and all three "
        "planes coded on both sides."
    )
    add("")
    add(figure("fig-anchor-gap"))
    add("")
    add(figure("fig-rd-curves"))
    add("")
    add(
        "The BD-rate of each anchor against the GIRC-explicit baseline is "
        f"{signed(anchors['akiyo_cif']['x265'], 2)}% for x265, "
        f"{signed(anchors['akiyo_cif']['svt-av1'], 2)}% for SVT-AV1 and "
        f"{signed(anchors['akiyo_cif']['vvenc'], 2)}% for VVenC: the anchors are "
        "better codecs, as expected, and the figure is the scale of the gap. The gap "
        "between the two GIRC lines is the mechanism."
    )
    add("")

    # -------------------------------------------------------------- pipeline
    add("## The pipeline")
    add("")
    add(figure("fig-architecture"))
    add("")
    add("## What is held constant")
    add("")
    add(
        "The two modes share the intra prediction, the quantization, the transform "
        "arithmetic, the residual coding and the entropy coder. They differ in one "
        "place: how the transform type reaches the decoder. A difference in the "
        "measured rate is therefore attributable to the signalling mechanism alone."
    )
    add("")
    add(
        "The transform arithmetic is the real thing. The integer transforms are "
        "bit-exact against Fraunhofer HHI's VVenC 1.14.0, checked by a test that "
        "drives the reference implementation's own kernels and compares the results "
        "bit for bit across all twelve transform and size combinations."
    )
    add("")

    # ---------------------------------------------------------------- portal
    add("## The portal and the hosted analysis")
    add("")
    add(
        "The portal is the confidential evaluation environment: organisation accounts, "
        "a versioned agreement, gated artifact delivery and an append-only audit log. "
        "The hosted analysis is the other half: post a sequence and get the same "
        "figures the benchmark writes, without building a toolchain first."
    )
    add("")
    add(figure("fig-evaluation-lifecycle"))
    add("")
    add(figure("fig-hosted-service"))
    add("")
    add(
        "The portal runs on one free Render instance, because a workspace gets 750 "
        "free instance hours a month and a month is 730 to 744 hours, so exactly one "
        "always-on free service fits. An UptimeRobot monitor pings `/health` every "
        "five minutes to keep the instance awake, since a free service sleeps after "
        "fifteen minutes idle."
    )
    add("")

    output = arguments.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {output.relative_to(ROOT)} ({len(lines)} lines, {len(list(FIGURES.glob('*.svg')))} figures available)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
