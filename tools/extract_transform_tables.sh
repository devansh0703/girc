#!/usr/bin/env bash
# Generate the VVC integer transform matrices used by `girc-core`.
#
# The matrices are the normative ITU-T H.266 (VVC) transform matrices for
# DCT-II, DCT-VIII and DST-VII. They are transcribed from Fraunhofer HHI's
# VVenC reference software (`source/Lib/CommonLib/RomTr.cpp`, Clear BSD
# License) and cross-checked against FFmpeg's `libavcodec/vvc/data.c`
# (LGPL-2.1+), which encodes the same tables from the standard.
#
# The macro definitions are expanded by the C preprocessor, so the emitted
# numbers are exactly what the reference implementation compiles to -- no
# hand-typed tables.
#
# Usage: tools/extract_transform_tables.sh <path/to/RomTr.cpp> <out.rs>
set -euo pipefail

SRC=${1:?usage: extract_transform_tables.sh <RomTr.cpp> <out.rs>}
OUT=${2:?usage: extract_transform_tables.sh <RomTr.cpp> <out.rs>}

WORK=$(mktemp -d "${TMPDIR:-/tmp}/girc-tbl.XXXXXX")
trap 'rm -rf "$WORK"' EXIT

# Pull out only the DEFINE_*_MATRIX macros and the four g_trCore* tables.
{
  echo '// Auto-extracted from VVenC RomTr.cpp (Clear BSD). Do not edit.'
  awk '/^#define DEFINE_(DCT2|DCT8|DST7)_P[0-9]+_MATRIX/,/^$/' "$SRC"
} > "$WORK/macros.h"

# The table declarations carry the parameter values; grab them verbatim.
# Strip the `ALIGN_DATA(...)` wrapper and the `const` qualifier so the
# declarations can be compiled into a plain C program. Each declaration spans
# three lines: the `ALIGN_DATA(...)` header, the opening brace, and the
# `DEFINE_*_MATRIX(...)` call, so pull a three-line window per table.
awk '
  /^ALIGN_DATA\( *MEMORY_ALIGN_DEF_SIZE, *const TMatrixCoeff g_trCore(DCT2|DCT8|DST7)P(4|8|16|32)\[/ {
    header = $0
    sub(/^ALIGN_DATA\( *MEMORY_ALIGN_DEF_SIZE, *const TMatrixCoeff /, "TCoeff ", header)
    sub(/ \) =$/, " =", header)
    print header
    getline; print            # opening brace
    getline; print            # DEFINE_*_MATRIX(...) call
    getline; print            # commented-out duplicate
    getline; print            # closing brace "};"
    print ""
    next
  }
' "$SRC" >> "$WORK/macros.h"

cat > "$WORK/dump.c" <<'EOF'
#include <stdio.h>
typedef short TMatrixCoeff;
typedef short TCoeff;
#define TRANSFORM_NUMBER_OF_DIRECTIONS 1
#define TRANSFORM_FORWARD 0
#define TRANSFORM_INVERSE 0
#include "macros.h"

static void dump(const char *kind, int n, const TMatrixCoeff m[n][n])
{
    printf("pub static %s%d: [i32; %d] = [\n", kind, n, n * n);
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++)
            printf("%s%d", j ? ", " : "", (int)m[i][j]);
        printf(",\n");
    }
    printf("];\n\n");
}

int main(void)
{
    dump("DCT2", 4, g_trCoreDCT2P4[0]);
    dump("DCT2", 8, g_trCoreDCT2P8[0]);
    dump("DCT2", 16, g_trCoreDCT2P16[0]);
    dump("DCT2", 32, g_trCoreDCT2P32[0]);
    dump("DCT8", 4, g_trCoreDCT8P4[0]);
    dump("DCT8", 8, g_trCoreDCT8P8[0]);
    dump("DCT8", 16, g_trCoreDCT8P16[0]);
    dump("DCT8", 32, g_trCoreDCT8P32[0]);
    dump("DST7", 4, g_trCoreDST7P4[0]);
    dump("DST7", 8, g_trCoreDST7P8[0]);
    dump("DST7", 16, g_trCoreDST7P16[0]);
    dump("DST7", 32, g_trCoreDST7P32[0]);
    return 0;
}
EOF

cc -I"$WORK" -o "$WORK/dump" "$WORK/dump.c" 2>"$WORK/cc.log" || {
  cat "$WORK/cc.log" >&2
  exit 1
}

{
  echo '//! VVC integer transform matrices (DCT-II, DCT-VIII, DST-VII).'
  echo '//!'
  echo '//! Generated by `tools/extract_transform_tables.sh` from the normative'
  echo '//! ITU-T H.266 tables as encoded in Fraunhofer HHI VVenC'
  echo '//! (`source/Lib/CommonLib/RomTr.cpp`, Clear BSD License).'
  echo '//! Cross-checked against FFmpeg `libavcodec/vvc/data.c` (LGPL-2.1+).'
  echo '//!'
  echo '//! Do not edit by hand; regenerate instead.'
  echo ''
  echo '#![allow(clippy::all)]'
  echo ''
  "$WORK/dump"
} > "$OUT"

echo "wrote $OUT"
