//! The chroma quantization parameter mapping.
//!
//! ITU-T H.266 does not quantize chroma at the luma quantization
//! parameter. The chroma quantization parameter is derived from the luma
//! one through a mapping table, so that the chroma planes are quantized at
//! a rate that suits their lower energy.
//!
//! # The derivation
//!
//! H.266 clause 8.6.3 derives the mapping table from a set of
//! breakpoints. The default breakpoints for 4:2:0 content are
//!
//! ```text
//! input  quantization parameter:  17  22  34  42
//! output quantization parameter:  17  23  35  39
//! ```
//!
//! and the table is built from them as follows.
//!
//! * The first breakpoint maps to itself: 17 becomes 17.
//! * Below the first breakpoint the mapping falls by one for each step,
//!   so 16 becomes 16 and 0 becomes 0.
//! * Between two breakpoints the mapping is linear. With `m` steps past
//!   the lower breakpoint, the value is the lower breakpoint's output
//!   plus `(output difference * m + rounding) / (input difference)`,
//!   where the rounding term is half the input difference.
//! * Above the last breakpoint the mapping rises by one for each step.
//!
//! Fraunhofer HHI's reference encoder, VVenC, builds the same table in
//! `ChromaQpMappingTable::derivedChromaQPMappingTables`, and the table
//! this module derives is checked against VVenC's own output for every
//! quantization parameter. The reference vectors are generated by
//! `tools/generate_chroma_qp_oracle.sh`.
//!
//! # Why the mapping matters here
//!
//! GIRC codes the chroma planes, so the chroma quantization parameter is
//! part of the codec rather than something the container carries. A
//! chroma plane quantized at the luma quantization parameter would be
//! coded at the wrong rate, and the anchor comparison would be unfair in
//! a way that has nothing to do with the mechanism under test.

/// The largest quantization parameter ITU-T H.266 defines.
pub const MAX_QP: i32 = 63;

/// The input breakpoints of the default 4:2:0 chroma mapping.
const INPUT_POINTS: [i32; 4] = [17, 22, 34, 42];

/// The output breakpoints of the default 4:2:0 chroma mapping.
const OUTPUT_POINTS: [i32; 4] = [17, 23, 35, 39];

/// The number of segments the breakpoints define.
const SEGMENTS: usize = INPUT_POINTS.len() - 1;

/// Build the chroma quantization parameter table.
///
/// This is the derivation from H.266 clause 8.6.3, written the way VVenC
/// writes it, so the two can be compared term for term.
const fn build_table() -> [i32; 64] {
    let mut table = [0i32; 64];

    // The difference between two breakpoints, less one: the number of
    // steps that separate them.
    let mut delta_in = [0i32; SEGMENTS];
    let mut delta_out = [0i32; SEGMENTS];
    let mut j = 0;
    while j < SEGMENTS {
        delta_in[j] = INPUT_POINTS[j + 1] - INPUT_POINTS[j] - 1;
        delta_out[j] = OUTPUT_POINTS[j + 1] - OUTPUT_POINTS[j];
        j += 1;
    }

    // The first breakpoint maps to itself, and below it the mapping falls
    // by one for each step.
    table[INPUT_POINTS[0] as usize] = OUTPUT_POINTS[0];
    let mut k = INPUT_POINTS[0] - 1;
    while k >= 0 {
        let value = table[(k + 1) as usize] - 1;
        table[k as usize] = if value < 0 { 0 } else { value };
        k -= 1;
    }

    // Between the breakpoints the mapping is linear.
    j = 0;
    while j < SEGMENTS {
        let shift = (delta_in[j] + 1) >> 1;
        let mut k = INPUT_POINTS[j] + 1;
        let mut m = 1;
        while k <= INPUT_POINTS[j + 1] {
            table[k as usize] =
                table[INPUT_POINTS[j] as usize] + ((delta_out[j] * m + shift) / (delta_in[j] + 1));
            k += 1;
            m += 1;
        }
        j += 1;
    }

    // Above the last breakpoint the mapping rises by one for each step.
    let mut k = INPUT_POINTS[SEGMENTS] + 1;
    while k <= MAX_QP {
        let value = table[(k - 1) as usize] + 1;
        table[k as usize] = if value > MAX_QP { MAX_QP } else { value };
        k += 1;
    }

    table
}

/// The chroma quantization parameter for each luma quantization
/// parameter, as ITU-T H.266 derives it.
pub static CHROMA_QP_TABLE: [i32; 64] = build_table();

/// The chroma quantization parameter for a luma quantization parameter.
///
/// The value is clamped to the range H.266 defines, so an out-of-range
/// luma quantization parameter still produces a usable chroma one.
pub fn chroma_qp(luma_qp: i32) -> i32 {
    CHROMA_QP_TABLE[luma_qp.clamp(0, MAX_QP) as usize]
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::chroma_qp_oracle_vectors::CHROMA_QP_FROM_LUMA_QP;

    /// The table must be exactly the one VVenC derives.
    ///
    /// The reference implementation is the oracle: the mapping is
    /// reproduced by the derivation in H.266 clause 8.6.3, and the
    /// vectors below are what the reference encoder produces. If the two
    /// ever disagree, one of them is wrong and the codec's chroma rate
    /// would be measured against the wrong baseline.
    #[test]
    fn the_table_matches_the_reference_encoder() {
        for (luma_qp, expected) in CHROMA_QP_FROM_LUMA_QP.iter().enumerate() {
            assert_eq!(
                chroma_qp(luma_qp as i32),
                *expected,
                "the chroma QP for luma QP {luma_qp} differs from the reference"
            );
        }
    }

    /// The mapping must rise with the luma quantization parameter.
    ///
    /// A quantization parameter that made the chroma *finer* as the
    /// luma got coarser would be a bug, and the monotone check catches
    /// any transcription error in the breakpoints.
    #[test]
    fn the_mapping_rises_with_the_luma_parameter() {
        for luma_qp in 1..=MAX_QP {
            assert!(
                chroma_qp(luma_qp) >= chroma_qp(luma_qp - 1),
                "the mapping falls between luma QP {} and {luma_qp}",
                luma_qp - 1
            );
        }
    }

    /// The first breakpoint maps to itself.
    #[test]
    fn the_first_breakpoint_maps_to_itself() {
        assert_eq!(chroma_qp(17), 17);
    }

    /// The breakpoints themselves map to their partners.
    #[test]
    fn the_breakpoints_map_to_their_partners() {
        for (input, output) in INPUT_POINTS.iter().zip(OUTPUT_POINTS.iter()) {
            assert_eq!(
                chroma_qp(*input),
                *output,
                "luma QP {input} must map to chroma QP {output}"
            );
        }
    }

    /// An out-of-range luma quantization parameter must not index out of
    /// the table.
    #[test]
    fn out_of_range_parameters_are_clamped() {
        assert_eq!(chroma_qp(-10), chroma_qp(0));
        assert_eq!(chroma_qp(1000), chroma_qp(MAX_QP));
    }
}
